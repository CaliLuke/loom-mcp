func TestGoldenUpdateNormalizesContentAndCanBeComparedWithoutUpdating(t *testing.T) {
	for _, tt := range []struct{ name, input, want string }{
		{"nested/document.json", `{"z":2,"a":1}`, "{\n  \"a\": 1,\n  \"z\": 2\n}\n"},
		{"source.go", "// Code generated by Loom v1.2.3, DO NOT EDIT.\npackage example\nfunc Value() int{return 42}", "// Code generated by Loom vX, DO NOT EDIT.\npackage example\n\nfunc Value() int { return 42 }\n"},
		{"plain.txt", "first  \r\nsecond\t", "first\nsecond\n"},
		{"schema.proto", "// Code generated with goa v1.2.3, DO NOT EDIT.\nsyntax = \"proto3\";\nmessage Item {}", "// Code generated with goa vX, DO NOT EDIT.\nsyntax = \"proto3\";\nmessage Item {}\n"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			golden := testutil.NewGoldenFile(t, dir)
			assert.False(t, golden.Exists(tt.name))
			golden.SetUpdateMode(true)
			golden.Compare(tt.input, tt.name)
			root, err := os.OpenRoot(dir)
			require.NoError(t, err)
			t.Cleanup(func() {
				require.NoError(t, root.Close())
			})
			data, err := root.ReadFile(tt.name)
			require.NoError(t, err)
			assert.Equal(t, tt.want, string(data))
			assert.True(t, golden.Exists(tt.name))
			assert.True(t, golden.Exists(filepath.Join(dir, tt.name)))
			golden.SetUpdateMode(false)
			golden.CompareBytes([]byte(tt.input), tt.name)
		})
	}
}

func TestGoldenPublicAssertionsNormalizeJSONAndGo(t *testing.T) {
	dir := t.TempDir()
	jsonPath := filepath.Join(dir, "value.json")
	require.NoError(t, os.WriteFile(jsonPath, []byte("{\n  \"a\": 1\n}\n"), 0600))
	testutil.AssertJSON(t, jsonPath, []byte(`{"a":1}`))
	goPath := filepath.Join(dir, "value.go")
	require.NoError(t, os.WriteFile(goPath, []byte("package example\n\nconst Value = 1\n"), 0600))
	testutil.AssertGo(t, goPath, "package example; const Value=1")
	testutil.AssertString(t, goPath, "package example; const Value=1")
	testutil.CompareOrUpdateGolden(t, "package example; const Value=1", goPath)
}
