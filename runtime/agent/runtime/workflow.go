package runtime

// workflow.go implements the durable plan/tool loop executed inside a workflow engine.
//
// Contract:
// - The workflow loop is deterministic and replay-safe: timeouts use workflow time.
// - The loop publishes lifecycle and tool events via hooks for streaming and persistence.
// - Helper methods in sibling workflow_*.go files are invoked by this loop; callers should
//   not call them directly outside of workflow execution.

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/api"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/compaction"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/engine"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/hooks"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/internal/cancellation"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/interrupt"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/model"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/planner"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/policy"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/run"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/runstore"
	"github.com/CaliLuke/loom-mcp/v2/runtime/agent/telemetry"
)

type workflowLoopStart struct {
	toolPolicy toolPolicyEnvelope
}

type workflowStartState struct {
	planInput     *workflowPlanInput
	firstOutput   *PlanActivityOutput
	timing        runTiming
	deadlines     runDeadlines
	caps          policy.CapsState
	nextAttempt   int
	parentTracker *childTracker
}

const (
	// Minimal viable timeout for scheduling an activity. If remaining time is
	// less than or equal to this value, the runtime should not schedule new work.
	minActivityTimeout = 3 * time.Second

	// Minimal viable grace period for finalization. If remaining time is
	// less than or equal to this value, the runtime should finalize with a user-facing message.
	defaultFinalizerGrace = 10 * time.Second
)

// ExecuteWorkflow is the main entry point for the generated workflow handler.
//
// Advanced & generated integration
//   - Intended to be invoked by code generated by loom-mcp during agent
//     registration, or by advanced users writing custom engine adapters.
//   - Normal applications should prefer the high‑level AgentClient API
//     (Runtime.Client(...).Run/Start) rather than calling this directly.
//
// It executes the agent's plan/tool loop using the configured planner, policy,
// and runtime hooks. Returns the final agent output or an error if the workflow
// fails. Generated code calls this from the workflow handler registered with
// the engine.
func (r *Runtime) ExecuteWorkflow(wfCtx engine.WorkflowContext, input *RunInput) (out *RunOutput, retErr error) {
	defer func() {
		retErr = hooks.WrapRunCompletionError(retErr)
	}()
	r.logWorkflowStart(wfCtx, input)
	reg, ctrl, runCtx, turnID, err := r.setupWorkflowExecution(wfCtx, input)
	if err != nil {
		return nil, err
	}
	protocolVersion := input.WorkflowProtocolVersion
	settings := cloneCompaction(input.ContextCompaction)
	recoverySettings := input.ContextRecovery
	agentSettings := cloneCompactionOptions(input.CompactionAgents)
	wfCtx = compactionWorkflowContext{WorkflowContext: wfCtx, settings: agentSettings, recovery: cloneRecoveryOptions(input.RecoveryAgents)}
	input, err = r.prepareEffectiveRunInput(wfCtx.Context(), reg, input, runCtx)
	if err != nil {
		return nil, err
	}
	if err := setRootRunIDQuery(wfCtx, input.RootRunID); err != nil {
		return nil, err
	}
	runCtx = workflowRunContext(input)
	defer r.cleanupWorkflowRun(input.RunID)
	planInput := &workflowPlanInput{AgentID: input.AgentID, RunContext: runCtx, protocolVersion: protocolVersion, compaction: settings, recovery: recoverySettings, contextSettings: input.ContextSettings}
	planInput.compactionState.Recall = compaction.NewRecall(input.ContextSettings.Settings)
	finalStatus := runStatusSuccess
	var finalErr error
	defer r.finishWorkflowExecution(wfCtx, input, planInput, runCtx, turnID, &out, &retErr, &finalStatus, &finalErr)
	if err := r.publishInitialWorkflowEvents(wfCtx.Context(), input, runCtx, turnID); err != nil {
		finalStatus, finalErr = workflowStatusForError(err), err
		return nil, err
	}

	var status string
	out, status, err = r.executeWorkflowRun(wfCtx, reg, input, planInput, turnID, ctrl)
	finalStatus = status
	finalErr = err
	return out, err
}

func validateWorkflowInput(input *RunInput) error {
	if input == nil {
		return fmt.Errorf("%w: run input is required", ErrInvalidConfig)
	}
	if input.WorkflowProtocolVersion != api.WorkflowProtocolVersion {
		return &api.WorkflowProtocolMismatchError{Want: api.WorkflowProtocolVersion, Got: input.WorkflowProtocolVersion}
	}
	if input.AgentID == "" {
		return errors.New("agent id is required")
	}
	if input.RootRunID == "" {
		return errors.New("root run id is required")
	}
	if input.Policy != nil && input.Policy.MaxRecoveryTurns < 0 {
		return fmt.Errorf("%w: MaxRecoveryTurns must not be negative", ErrInvalidConfig)
	}
	return nil
}

func workflowRunContext(input *RunInput) run.Context {
	labels := cloneLabels(input.Labels)
	delete(labels, FinalizationReasonLabel)
	return run.Context{
		RunID:            input.RunID,
		RootRunID:        input.RootRunID,
		SessionID:        input.SessionID,
		TurnID:           input.TurnID,
		ParentToolCallID: input.ParentToolCallID,
		ParentRunID:      input.ParentRunID,
		ParentAgentID:    input.ParentAgentID,
		Tool:             input.Tool,
		ToolArgs:         input.ToolArgs,
		Attempt:          1,
		Labels:           labels,
	}
}

// planningDeadlines starts the active budget after caller history is stored,
// preserving the pre-index boundary between run setup and planning work.
func planningDeadlines(now time.Time, timing runTiming) runDeadlines {
	deadlines := runDeadlines{FinalizerGrace: timing.FinalizerGrace}
	if timing.TimeBudget > 0 {
		deadlines.Budget = now.Add(timing.TimeBudget)
		deadlines.Hard = deadlines.Budget.Add(timing.FinalizerGrace)
	}
	return deadlines
}

func workflowStatusForError(err error) string {
	if err == nil {
		return runStatusSuccess
	}
	return terminalRunStatusForError(err)
}

func applyWorkflowCaps(caps policy.CapsState, input *RunInput) policy.CapsState {
	if input.Policy == nil {
		return caps
	}
	if input.Policy.MaxToolCalls > 0 {
		caps.MaxToolCalls = input.Policy.MaxToolCalls
		caps.RemainingToolCalls = input.Policy.MaxToolCalls
	}
	if input.Policy.MaxRecoveryTurns > 0 {
		caps.MaxRecoveryTurns = input.Policy.MaxRecoveryTurns
		caps.RemainingRecoveryTurns = input.Policy.MaxRecoveryTurns
	}
	return caps
}

func setRootRunIDQuery(wfCtx engine.WorkflowContext, rootRunID string) error {
	if err := setToolAwaitsQuery(wfCtx, nil); err != nil {
		return err
	}
	return wfCtx.SetQueryHandler(api.QueryRootRunID, func() (string, error) {
		return rootRunID, nil
	})
}

func resolveRunLoopActivityOptions(reg AgentRegistration, input *RunInput) (engine.ActivityOptions, engine.ActivityOptions) {
	resumeOpts := reg.ResumeActivityOptions
	if input.Policy != nil && input.Policy.PlanTimeout > 0 {
		resumeOpts.StartToCloseTimeout = input.Policy.PlanTimeout
	}
	toolOpts := reg.ExecuteToolActivityOptions
	if input.Policy != nil && input.Policy.ToolTimeout > 0 {
		toolOpts.StartToCloseTimeout = input.Policy.ToolTimeout
	}
	if toolOpts.StartToCloseTimeout == 0 {
		toolOpts.StartToCloseTimeout = defaultExecuteToolActivityTimeout
	}
	return resumeOpts, toolOpts
}

// timeoutUntil returns the remaining duration until deadline, relative to now.
// The ok result is false when deadline is non-zero and has already elapsed.
func timeoutUntil(deadline, now time.Time) (time.Duration, bool) {
	if deadline.IsZero() {
		return 0, true
	}
	rem := deadline.Sub(now)
	if rem <= 0 {
		return 0, false
	}
	return rem, true
}

// seedWorkflowPlan keeps caller history out of the first planner Pending slice.
func seedWorkflowPlan(wfCtx engine.WorkflowContext, input *RunInput, planInput *workflowPlanInput, startReq *PlanActivityInput) error {
	seed, err := seedWorkflowIndex(wfCtx, input)
	if err != nil {
		return err
	}
	planInput.Entries, planInput.IndexHead = seed.Entries, seed.IndexHead
	planInput.Committed = len(seed.Entries)
	startReq.View = planInput.view()
	return nil
}

func (r *Runtime) prepareEffectiveRunInput(ctx context.Context, reg AgentRegistration, input *RunInput, runCtx run.Context) (*RunInput, error) {
	effective, err := runBeforeRunInterceptors(ctx, r.interceptorsForAgent(input.AgentID), *input, runCtx)
	if err != nil {
		return nil, err
	}
	if err := r.validateTerminalPolicies(reg, &effective); err != nil {
		return nil, err
	}
	return &effective, nil
}

func (r *Runtime) cleanupWorkflowRun(runID string) {
	r.storeWorkflowHandle(runID, nil)
	if r.reminders != nil {
		r.reminders.ClearRun(runID)
	}
}

func (r *Runtime) finishWorkflowExecution(
	wfCtx engine.WorkflowContext,
	input *RunInput,
	planInput *workflowPlanInput,
	runCtx run.Context,
	turnID string,
	out **RunOutput,
	retErr *error,
	finalStatus *string,
	finalErr *error,
) {
	*finalErr = cancellation.Sanitize(*finalErr)
	afterOut, afterErr := runAfterRunInterceptors(wfCtx.Context(), r.interceptorsForAgent(input.AgentID), *input, runCtx, *out, *finalErr)
	*out = afterOut
	*finalErr = cancellation.Sanitize(afterErr)
	*retErr = afterErr
	if *finalErr != nil {
		*finalStatus = terminalRunStatusForError(*finalErr)
	} else if *finalStatus != runStatusSuccess {
		*finalStatus = runStatusSuccess
	}
	if err := r.sealWorkflowRecord(wfCtx, input, planInput); err != nil {
		*finalErr = errors.Join(*finalErr, err)
		*retErr = *finalErr
		*finalStatus = runStatusFailed
	}
	r.publishWorkflowCompletion(wfCtx, input, turnID, finalStatus, finalErr)
}

func (r *Runtime) setupWorkflowExecution(
	wfCtx engine.WorkflowContext,
	input *RunInput,
) (AgentRegistration, *interrupt.Controller, run.Context, string, error) {
	if err := validateWorkflowInput(input); err != nil {
		return AgentRegistration{}, nil, run.Context{}, "", err
	}
	reg, ok := r.agentByID(input.AgentID)
	if !ok {
		return AgentRegistration{}, nil, run.Context{}, "", fmt.Errorf("agent %q is not registered", input.AgentID)
	}
	if input.ContextCompaction != nil && reg.Policy.History != nil {
		return AgentRegistration{}, nil, run.Context{}, "", fmt.Errorf("%w: context compaction cannot be combined with HistoryPolicy", ErrInvalidConfig)
	}
	r.logger.Info(wfCtx.Context(), "Agent found, executing plan activity", "agent_id", input.AgentID)
	return reg, interrupt.NewController(wfCtx), workflowRunContext(input), input.TurnID, nil
}

func (r *Runtime) logWorkflowStart(wfCtx engine.WorkflowContext, input *RunInput) {
	if r.logger != nil {
		r.logger.Info(wfCtx.Context(), "ExecuteWorkflow called", "agent_id", input.AgentID, "run_id", input.RunID)
	}
}

func (r *Runtime) publishInitialWorkflowEvents(ctx context.Context, input *RunInput, runCtx run.Context, turnID string) error {
	if err := r.publishHook(ctx, hooks.NewRunStartedEvent(input.RunID, input.AgentID, runCtx, *input), turnID); err != nil {
		return err
	}
	return r.publishHook(ctx, hooks.NewRunPhaseChangedEvent(input.RunID, input.AgentID, input.SessionID, run.PhasePrompted), turnID)
}

func (r *Runtime) publishWorkflowCompletion(
	wfCtx engine.WorkflowContext,
	input *RunInput,
	turnID string,
	finalStatus *string,
	finalErr *error,
) {
	phase := terminalRunPhaseForStatus(*finalStatus)
	detached := wfCtx.Detached()
	termCtx, cancel := context.WithTimeout(detached.Context(), 10*time.Second)
	defer cancel()
	if err := r.publishHookErr(
		termCtx,
		hooks.NewRunCompletedEvent(input.RunID, input.AgentID, input.SessionID, *finalStatus, phase, *finalErr),
		turnID,
	); err != nil {
		r.logWarn(termCtx, "run completed hook failed", err, "run_id", input.RunID, "agent_id", input.AgentID)
	}
}

func (r *Runtime) prepareWorkflowPlanning(reg AgentRegistration, input *RunInput, base *workflowPlanInput) (PlanActivityInput, runTiming) {
	return PlanActivityInput{
		AgentID: input.AgentID, RunID: input.RunID, RunContext: base.RunContext, CallFilter: planToolFilter(input),
	}, resolveRunTiming(reg, input)
}

func (r *Runtime) executeWorkflowRun(
	wfCtx engine.WorkflowContext,
	reg AgentRegistration,
	input *RunInput,
	planInput *workflowPlanInput,
	turnID string,
	ctrl *interrupt.Controller,
) (*RunOutput, string, error) {
	state, err := r.startWorkflowRun(wfCtx, reg, input, planInput, turnID)
	if err != nil {
		return r.handleWorkflowStartError(wfCtx, reg, input, state, turnID, err)
	}
	return r.continueWorkflowRun(wfCtx, reg, input, state, turnID, ctrl)
}

func (r *Runtime) handleWorkflowStartError(
	wfCtx engine.WorkflowContext,
	reg AgentRegistration,
	input *RunInput,
	state workflowStartState,
	turnID string,
	startErr error,
) (*RunOutput, string, error) {
	if state.planInput == nil {
		return nil, workflowStatusForError(startErr), startErr
	}
	reason := planner.TerminationReasonFailureCap
	if state.deadlines.budgetExpired(wfCtx.Now()) {
		reason = planner.TerminationReasonTimeBudget
	} else if !boundedErrorIs(startErr, errRecoveryTurnCapExceeded) || state.firstOutput == nil {
		return nil, workflowStatusForError(startErr), startErr
	}
	var usage model.TokenUsage
	var notes []planner.PlannerAnnotation
	if state.firstOutput != nil {
		usage = state.firstOutput.Usage
		notes = plannerResultNotes(state.firstOutput.Result)
	}
	out, err := r.finalizeWithPlanner(
		wfCtx,
		reg,
		input,
		state.planInput,
		nil,
		usage,
		state.caps,
		state.nextAttempt,
		turnID,
		notes,
		reason,
		state.deadlines.Hard,
	)
	if err != nil {
		return nil, workflowStatusForError(err), err
	}
	return out, runStatusSuccess, nil
}

func (r *Runtime) continueWorkflowRun(wfCtx engine.WorkflowContext, reg AgentRegistration, input *RunInput, state workflowStartState, turnID string, ctrl *interrupt.Controller) (*RunOutput, string, error) {
	planInput, firstOutput := state.planInput, state.firstOutput
	r.logger.Info(wfCtx.Context(), "Starting runLoop", "tool_calls", len(firstOutput.Result.ToolCalls))
	out, err := r.runLoop(
		wfCtx,
		reg,
		input,
		planInput,
		firstOutput.Result,
		firstOutput.TranscriptRef,
		firstOutput.Usage,
		state.caps,
		state.deadlines.Budget,
		state.deadlines.Hard,
		state.nextAttempt,
		turnID,
		state.parentTracker,
		ctrl,
		state.timing.FinalizerGrace,
		workflowLoopStart{toolPolicy: toolPolicyEnvelope{
			Active:  firstOutput.ToolPolicyActive,
			Allowed: cloneToolIdents(firstOutput.AllowedTools),
		}},
	)
	if err != nil {
		return nil, terminalRunStatusForError(err), err
	}
	return out, runStatusSuccess, nil
}

func (r *Runtime) startWorkflowRun(
	wfCtx engine.WorkflowContext,
	reg AgentRegistration,
	input *RunInput,
	planInput *workflowPlanInput,
	turnID string,
) (workflowStartState, error) {
	startReq, timing := r.prepareWorkflowPlanning(reg, input, planInput)
	state := workflowStartState{
		planInput:   planInput,
		timing:      timing,
		caps:        applyWorkflowCaps(initialCaps(reg.Policy), input),
		nextAttempt: startReq.RunContext.Attempt + 1,
	}
	if err := seedWorkflowPlan(wfCtx, input, planInput, &startReq); err != nil {
		return state, err
	}
	state.deadlines = planningDeadlines(wfCtx.Now(), timing)
	policyResult, err := r.preparePrePlanToolPolicy(wfCtx.Context(), reg, input, planInput, state.caps, turnID)
	if err != nil {
		return state, err
	}
	state.caps = policyResult.Caps
	startReq.ToolPolicyActive = policyResult.Envelope.Active
	startReq.ToolsDisabled = policyResult.Envelope.Disabled
	startReq.AllowedTools = cloneToolIdents(policyResult.Envelope.Allowed)
	startReq.PolicyCaps = state.caps
	startReq.RunContext.Labels = cloneLabels(planInput.RunContext.Labels)
	if err := enforcePlanActivityInputBudget(startReq); err != nil {
		return state, err
	}
	planOpts := r.resolveAndLogWorkflowTiming(wfCtx, reg, input, timing)
	if err := r.publishPlanningPhase(wfCtx.Context(), input, turnID); err != nil {
		return state, err
	}
	state.firstOutput, err = r.runInitialPlan(wfCtx, &state, reg, input, startReq, planOpts)
	state.adoptInitialPlan(planInput)
	return state, err
}

func (r *Runtime) resolveAndLogWorkflowTiming(
	wfCtx engine.WorkflowContext,
	reg AgentRegistration,
	input *RunInput,
	timing runTiming,
) engine.ActivityOptions {
	planOpts := reg.PlanActivityOptions
	if input.Policy != nil && input.Policy.PlanTimeout > 0 {
		planOpts.StartToCloseTimeout = input.Policy.PlanTimeout
	}
	if r.logger != nil {
		toolTimeout := reg.ExecuteToolActivityOptions.StartToCloseTimeout
		if toolTimeout == 0 {
			toolTimeout = defaultExecuteToolActivityTimeout
		}
		if input.Policy != nil && input.Policy.ToolTimeout > 0 {
			toolTimeout = input.Policy.ToolTimeout
		}
		r.logger.Info(wfCtx.Context(), "timing_resolved",
			"time_budget", timing.TimeBudget,
			"finalizer_grace", timing.FinalizerGrace,
			"hard_deadline", func() time.Time {
				if timing.TimeBudget <= 0 {
					return time.Time{}
				}
				return wfCtx.Now().Add(timing.TimeBudget + timing.FinalizerGrace)
			}(),
			"plan_timeout", planOpts.StartToCloseTimeout,
			"tool_timeout", toolTimeout,
		)
	}
	return planOpts
}

func (r *Runtime) publishPlanningPhase(ctx context.Context, input *RunInput, turnID string) error {
	return r.publishHook(ctx, hooks.NewRunPhaseChangedEvent(input.RunID, input.AgentID, input.SessionID, run.PhasePlanning), turnID)
}

func (r *Runtime) validateFirstPlanOutput(ctx context.Context, output *PlanActivityOutput) error {
	if output == nil || output.Result == nil {
		r.logger.Error(ctx, "Plan activity returned nil result")
		return fmt.Errorf("plan activity returned nil result")
	}
	r.logger.Info(ctx, "Plan activity completed", "tool_calls", len(output.Result.ToolCalls), "final_response", output.Result.FinalResponse != nil)
	return nil
}

func (r *Runtime) runInitialPlan(wfCtx engine.WorkflowContext, state *workflowStartState, reg AgentRegistration, input *RunInput, startReq PlanActivityInput, planOpts engine.ActivityOptions) (*PlanActivityOutput, error) {
	firstOutput, err := r.runPlanActivityRecovering(wfCtx, state.planInput, reg.PlanActivityName, planOpts, startReq, state.deadlines.Budget, &state.caps, &state.nextAttempt, func(output *PlanActivityOutput) (hooks.Event, error) {
		// Preparation is pure workflow-side computation. Complete it before the
		// adoption/phase batch so a preparation failure never announces execution.
		caps, next, parent, err := r.prepareWorkflowLoopState(wfCtx.Context(), reg, input, state.planInput, output.Result, output)
		if err != nil {
			return nil, err
		}
		state.caps, state.nextAttempt, state.parentTracker = caps, next, parent
		return hooks.NewRunPhaseChangedEvent(startReq.RunID, startReq.AgentID, startReq.RunContext.SessionID, run.PhaseExecutingTools), nil
	})
	if err != nil {
		r.logger.Error(wfCtx.Context(), "Plan activity failed", "error", err)
		return firstOutput, err
	}
	if err := r.validateFirstPlanOutput(wfCtx.Context(), firstOutput); err != nil {
		return nil, err
	}
	return firstOutput, nil
}

func (r *Runtime) prepareWorkflowLoopState(
	ctx context.Context,
	reg AgentRegistration,
	input *RunInput,
	planInput *workflowPlanInput,
	result *planner.PlanResult,
	output *PlanActivityOutput,
) (policy.CapsState, int, *childTracker, error) {
	if len(result.ToolCalls) == 0 && result.FinalResponse == nil && result.FinalToolResult == nil && result.Await == nil {
		return policy.CapsState{}, 0, nil, fmt.Errorf("plan result has no tool calls, final response, final tool result, or await")
	}
	if len(result.ToolCalls) == 0 && (result.FinalResponse != nil || result.FinalToolResult != nil) {
		r.logger.Info(ctx, "PlanResult has a terminal result but no ToolCalls - workflow will return early")
	}
	caps := applyWorkflowCaps(initialCaps(reg.Policy), input)
	if output != nil && (output.PolicyCaps.MaxToolCalls > 0 || output.PolicyCaps.MaxRecoveryTurns > 0) {
		caps = output.PolicyCaps
	}
	var parentTracker *childTracker
	if planInput.RunContext.ParentToolCallID != "" {
		parentTracker = newChildTracker(planInput.RunContext.ParentToolCallID)
	}
	nextAttempt := planInput.RunContext.Attempt + 1
	if output != nil && output.Attempt > 0 {
		nextAttempt = output.Attempt + 1
	}
	return caps, nextAttempt, parentTracker, nil
}

// runLoop executes the plan/tool/resume cycle until the planner returns a final response
// or a cap/deadline is exceeded. The turnID parameter enables turn-based event stamping.
func (r *Runtime) runLoop(
	wfCtx engine.WorkflowContext,
	reg AgentRegistration,
	input *RunInput,
	base *workflowPlanInput,
	initialResult *planner.PlanResult,
	initialTranscript runstore.Hash,
	initialUsage model.TokenUsage,
	caps policy.CapsState,
	budgetDeadline time.Time,
	hardDeadline time.Time,
	nextAttempt int,
	turnID string,
	parentTracker *childTracker,
	ctrl *interrupt.Controller,
	finalizerGrace time.Duration,
	initialStates ...workflowLoopStart,
) (*RunOutput, error) {
	if err := r.validateRunLoopInputs(base, initialResult); err != nil {
		return nil, err
	}
	ctx := wfCtx.Context()
	r.ensureWorkflowLogger()
	r.logRunLoopStart(ctx, initialResult)
	var initial workflowLoopStart
	if len(initialStates) > 0 {
		initial = initialStates[0]
	}
	st := newRunLoopState(initialResult, initialTranscript, initialUsage, caps, nextAttempt, initial.toolPolicy)
	resumeOpts, toolOpts := resolveRunLoopActivityOptions(reg, input)

	loop := newWorkflowLoop(
		r,
		wfCtx,
		reg,
		input,
		base,
		st,
		turnID,
		ctrl,
		parentTracker,
		runDeadlines{
			Budget:         budgetDeadline,
			Hard:           hardDeadline,
			FinalizerGrace: finalizerGrace,
		},
		resumeOpts,
		toolOpts,
	)
	return loop.run()
}

func (r *Runtime) validateRunLoopInputs(base *workflowPlanInput, initialResult *planner.PlanResult) error {
	if base == nil {
		return errors.New("base plan input is required")
	}
	if initialResult == nil {
		return fmt.Errorf("runLoop initial PlanResult is nil")
	}
	if len(initialResult.ToolCalls) == 0 && initialResult.FinalResponse == nil && initialResult.FinalToolResult == nil && initialResult.Await == nil {
		return fmt.Errorf("runLoop initial PlanResult has no ToolCalls, FinalResponse, FinalToolResult, or Await")
	}
	return nil
}

func (r *Runtime) ensureWorkflowLogger() {
	if r.logger == nil {
		r.logger = telemetry.NoopLogger{}
	}
}

func (r *Runtime) logRunLoopStart(ctx context.Context, initialResult *planner.PlanResult) {
	r.logger.Info(ctx, "runLoop starting iteration", "tool_calls", len(initialResult.ToolCalls), "final_response", initialResult.FinalResponse != nil, "final_tool_result", initialResult.FinalToolResult != nil, "await", initialResult.Await != nil)
}

// adoptInitialPlan records the flushed head even when planner recovery advanced
// the attempt before the workflow loop began.
func (state *workflowStartState) adoptInitialPlan(planInput *workflowPlanInput) {
	if state.firstOutput != nil {
		planInput.adopt(state.firstOutput)
	}
	if state.firstOutput != nil && state.firstOutput.Attempt > 0 {
		planInput.RunContext.Attempt = state.firstOutput.Attempt
	}
}
